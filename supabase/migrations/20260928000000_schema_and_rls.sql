-- Yeni kullanıcı → profiles satırı
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, kvkk_accepted_at)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
    CASE WHEN NEW.raw_user_meta_data ? 'kvkk_accepted_at'
         THEN (NEW.raw_user_meta_data->>'kvkk_accepted_at')::timestamptz END
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION handle_new_user();

-- Restore öncesi oluşmuş ama profili olmayan kullanıcılar
INSERT INTO profiles (id, email, full_name)
SELECT u.id, u.email, split_part(u.email, '@', 1) FROM auth.users u
ON CONFLICT (id) DO NOTHING;

-- auth.users üzerinde başka isimli eski bir profil trigger'ı varsa çift insert olur; uyar.
DO $
DECLARE t RECORD;
BEGIN
  FOR t IN SELECT tgname FROM pg_trigger
           WHERE tgrelid = 'auth.users'::regclass AND NOT tgisinternal AND tgname <> 'on_auth_user_created'
  LOOP
    RAISE NOTICE 'auth.users üzerinde ek trigger var: % — profil oluşturuyorsa kaldırın (DROP TRIGGER % ON auth.users)', t.tgname, t.tgname;
  END LOOP;
END $;

-- Takip edilen mekâna yeni onaylı etkinlik → bildirim.
-- SECURITY DEFINER: notifications tablosuna RLS'e takılmadan yazar.
CREATE OR REPLACE FUNCTION handle_new_event_notification()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NEW.is_approved AND (TG_OP = 'INSERT' OR NOT COALESCE(OLD.is_approved, FALSE)) THEN
    INSERT INTO notifications (user_id, title, message, link)
    SELECT f.user_id,
           'Yeni Etkinlik: ' || NEW.venue_name,
           NEW.title || ' etkinliği eklendi! Biletler tükenmeden göz at.',
           '/etkinlik/' || NEW.id
    FROM follows f
    WHERE f.entity_type = 'venue' AND f.entity_id = NEW.venue_name;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_event_created ON events;
CREATE TRIGGER on_event_created
AFTER INSERT OR UPDATE OF is_approved ON events
FOR EACH ROW EXECUTE FUNCTION handle_new_event_notification();

