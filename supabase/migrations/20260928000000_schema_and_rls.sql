-- Popülerlik sıralaması için favori sayıları (kimin favorilediğini açığa çıkarmaz)
CREATE OR REPLACE VIEW event_favorite_counts AS
SELECT event_id, COUNT(*)::INTEGER AS favorite_count
FROM favorites
GROUP BY event_id;

CREATE OR REPLACE VIEW event_ratings AS
SELECT event_id, COUNT(*) AS review_count, ROUND(AVG(rating)::numeric, 1) AS avg_rating
FROM event_reviews
WHERE status = 'approved'
GROUP BY event_id;

GRANT SELECT ON event_favorite_counts, event_ratings TO anon, authenticated;

