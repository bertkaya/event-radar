-- Eski / elle eklenmiş politikaları temizle (ör. "Enable all access")
DO $$
DECLARE p RECORD;
BEGIN
  FOR p IN
    SELECT schemaname, tablename, policyname FROM pg_policies
    WHERE schemaname = 'public' AND tablename IN (
      'events','venues','organizers','tags','profiles','favorites','analytics',
      'venue_applications','event_suggestions','follows','notifications',
      'scraper_logs','event_clicks','event_reviews','promotions')
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON %I.%I', p.policyname, p.schemaname, p.tablename);
  END LOOP;
END $$;

-- events: herkes onaylıları okur; giriş yapmış kullanıcı onaysız öneri ekler (/venue)
CREATE POLICY events_public_read ON events FOR SELECT
  USING (is_approved = TRUE);
CREATE POLICY events_owner_read ON events FOR SELECT TO authenticated
  USING (owner_id = auth.uid());
CREATE POLICY events_user_submit ON events FOR INSERT TO authenticated
  WITH CHECK (owner_id = auth.uid() AND is_approved = FALSE AND COALESCE(is_featured, FALSE) = FALSE);

-- Referans tablolar: herkese açık okuma. venues'ta iletişim kolonları gizli (aşağıda).
CREATE POLICY venues_public_read ON venues FOR SELECT USING (TRUE);
CREATE POLICY organizers_public_read ON organizers FOR SELECT USING (TRUE);
CREATE POLICY tags_public_read ON tags FOR SELECT USING (TRUE);
CREATE POLICY promotions_public_read ON promotions FOR SELECT
  USING (is_active = TRUE AND (end_date IS NULL OR end_date > NOW()));

-- profiles: yalnızca kendi satırı
CREATE POLICY profiles_self_read ON profiles FOR SELECT TO authenticated USING (id = auth.uid());
CREATE POLICY profiles_self_insert ON profiles FOR INSERT TO authenticated WITH CHECK (id = auth.uid());
CREATE POLICY profiles_self_update ON profiles FOR UPDATE TO authenticated
  USING (id = auth.uid()) WITH CHECK (id = auth.uid());

-- favorites / follows: yalnızca kendi satırları (sayılar event_favorite_counts view'undan)
CREATE POLICY favorites_self_all ON favorites FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
CREATE POLICY follows_self_all ON follows FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- notifications: kendi bildirimini okur / okundu işaretler
CREATE POLICY notifications_self_read ON notifications FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE POLICY notifications_self_update ON notifications FOR UPDATE TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- analytics / event_clicks: anonim yazma, okuma yok
CREATE POLICY analytics_insert ON analytics FOR INSERT
  WITH CHECK (action_type IN ('favorite', 'share', 'calendar', 'ticket', 'view', 'directions'));
CREATE POLICY event_clicks_insert ON event_clicks FOR INSERT WITH CHECK (TRUE);

-- event_reviews: onaylıları herkes okur; kullanıcı kendi yorumunu 'pending' olarak ekler
CREATE POLICY reviews_public_read ON event_reviews FOR SELECT USING (status = 'approved');
CREATE POLICY reviews_self_read ON event_reviews FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE POLICY reviews_self_insert ON event_reviews FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid() AND status = 'pending' AND COALESCE(is_verified, FALSE) = FALSE);

